func savePNG(path string, img image.Image) error {
	var buf bytes.Buffer
	if err := png.Encode(&buf, img); err != nil {
		return err
	}
	return os.WriteFile(path, buf.Bytes(), 0o644)
}

func decodePNG(data []byte) (*image.RGBA, error) {
	img, err := png.Decode(bytes.NewReader(data))
	if err != nil {
		return nil, err
	}
	if r, ok := img.(*image.RGBA); ok {
		return r, nil
	}
	b := img.Bounds()
	out := image.NewRGBA(image.Rect(0, 0, b.Dx(), b.Dy()))
	for y := 0; y < b.Dy(); y++ {
		for x := 0; x < b.Dx(); x++ {
			out.Set(x, y, img.At(b.Min.X+x, b.Min.Y+y))
		}
	}
	return out, nil
}

// writeReport emits the machine-generated portion of REPORT.md: the run header
// and the per-URL fidelity+speed table. The hand-written honest analysis lives
// below the AUTO-GENERATED marker and is preserved across re-runs.
func writeReport(path string, results []Result, w, h, n int, chromeBin string) error {
	var b strings.Builder
	fmt.Fprintf(&b, "# webengine vs headless Chromium — comparison report\n\n")
	fmt.Fprintf(&b, "<!-- AUTO-GENERATED: this header, the results table and the montage list are "+
		"regenerated by `go run ./cmd/compare`. The hand-written analysis below the "+
		"BEGIN ANALYSIS marker is preserved across re-runs. -->\n\n")
	fmt.Fprintf(&b, "**Generated:** %s  \n", time.Now().UTC().Format("2006-01-02 15:04 UTC"))
	fmt.Fprintf(&b, "**Viewport:** %d×%d, device-scale 1  \n", w, h)
	fmt.Fprintf(&b, "**Timing:** median of N=%d runs after 1 warmup, wall-clock incl. network fetch  \n", n)
	fmt.Fprintf(&b, "**Chrome:** `%s`  \n", chromeBin)
	fmt.Fprintf(&b, "**Fidelity region:** common top-left overlap of the two full-page renders, "+
		"capped to the top rows shown in the `region` column "+
		"(SSIM windowed 8px/step4 over luminance; pixdiff = %% pixels with max-channel Δ>16).\n\n")

	fmt.Fprintf(&b, "<!-- BEGIN RESULTS TABLE -->\n")
	fmt.Fprintf(&b, "| URL | SSIM | pixdiff %% | webengine ms | chrome ms | speed× | region | status |\n")
	fmt.Fprintf(&b, "|-----|-----:|----------:|-------------:|----------:|-------:|:------:|:------:|\n")
	for _, r := range results {
		status := "ok"
		switch {
		case !r.WebengineOK && !r.ChromeOK:
			status = "both failed"
		case !r.WebengineOK:
			status = "webengine failed"
		case !r.ChromeOK:
			status = "chrome failed"
		}
		if r.WebengineOK && r.ChromeOK {
			fmt.Fprintf(&b, "| %s | %.3f | %.1f | %.1f | %.1f | %.2f | %d×%d | %s |\n",
				shortURL(r.URL), r.SSIM, r.PixDiffPct, r.WebengineMs, r.ChromeMs, r.SpeedRatio,
				r.RegionW, r.RegionH, status)
		} else {
			we := naOr(r.WebengineOK, r.WebengineMs)
			ch := naOr(r.ChromeOK, r.ChromeMs)
			fmt.Fprintf(&b, "| %s | – | – | %s | %s | – | – | %s |\n",
				shortURL(r.URL), we, ch, status)
		}
	}
	fmt.Fprintf(&b, "<!-- END RESULTS TABLE -->\n\n")

	fmt.Fprintf(&b, "Speed× is `chrome_ms / webengine_ms`: >1 means webengine is faster.\n\n")

	// Montage links.
	fmt.Fprintf(&b, "## Montages (webengine | chrome | diff-heatmap)\n\n")
	for _, r := range results {
		if r.WebengineOK && r.ChromeOK {
			fmt.Fprintf(&b, "### %s\n\n![%s](%s)\n\n", shortURL(r.URL), shortURL(r.URL), r.Montage)
		} else {
			fmt.Fprintf(&b, "### %s\n\n_no montage: %s_\n\n", shortURL(r.URL), r.Note)
		}
	}

	// Preserve any hand-written analysis appended after the marker on a prior run.
	analysis := loadAnalysis(path)
	b.WriteString(analysis)

	return os.WriteFile(path, []byte(b.String()), 0o644)
}

const analysisMarker = "<!-- BEGIN ANALYSIS (hand-written, preserved across re-runs) -->"

// loadAnalysis returns the hand-written analysis section (from analysisMarker to
// EOF) of an existing report, or a default template if none exists.
func loadAnalysis(path string) string {
	if data, err := os.ReadFile(path); err == nil {
		if i := strings.Index(string(data), analysisMarker); i >= 0 {
			return string(data)[i:]
		}
	}
	return analysisMarker + "\n\n## Honest analysis\n\n" +
		"_Fill in after the first run: where webengine is at/above parity and where the gap is large._\n"
}

func shortURL(u string) string {
	s := strings.TrimPrefix(u, "https://")
	s = strings.TrimPrefix(s, "http://")
	return s
}

func naOr(ok bool, ms float64) string {
	if ok {
		return fmt.Sprintf("%.1f", ms)
	}
	return "–"
}
